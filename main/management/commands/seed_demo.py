class Command(BaseCommand):
    help = "Заполняет сайт демо-контентом, если он ещё пустой"

    def handle(self, *args, **options):
        if not SiteSettings.objects.exists():
            SiteSettings.objects.create(
                company_name="Чисто",
                hero_title="Уборка, после которой хочется жить дома",
                hero_subtitle="Убираем квартиры, дома и офисы. Своя химия и инвентарь, фиксированная цена и гарантия результата.",
                phone="+7 (000) 000-00-00",
                email="hello@example.com",
                address="ул. Пушкина, 10, офис 5",
                work_hours="ежедневно 8:00–22:00",
            )

        if not Service.objects.exists():
            for order, (title, text, price, unit, icon) in enumerate(SERVICES):
                Service.objects.create(
                    title=title, description=text, price_from=price, unit=unit, icon=icon, order=order
                )

        if not Review.objects.exists():
            for author, text, rating in REVIEWS:
                Review.objects.create(author=author, text=text, rating=rating)

        if not Faq.objects.exists():
            for order, (question, answer) in enumerate(FAQS):
                Faq.objects.create(question=question, answer=answer, order=order)

        self.stdout.write(self.style.SUCCESS("Демо-контент на месте"))
